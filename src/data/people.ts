export function getPerson(id: string) {
  return PEOPLE.find((p) => p.id === id);
}

export function fullName(p: Pick<Person, "firstName" | "lastName">) {
  return `${p.firstName} ${p.lastName}`;
}

/** "The Whitfield family" when there's a household, otherwise the person's name. */
export function householdName(p: Person) {
  return p.household.length > 0 ? `The ${p.lastName} family` : fullName(p);
}

export function countByStage(people: Person[] = PEOPLE) {
  const counts = Object.fromEntries(PIPELINE.map(({ stage }) => [stage, 0])) as Record<PipelineStage, number>;
  for (const p of people) counts[p.stage] += 1;
  return counts;
}
